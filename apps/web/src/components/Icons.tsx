/**
 * Inline SVG icons.
 *
 * Hand-written rather than pulled from an icon package: the UI needs seven
 * shapes, and inlining them avoids a dependency and keeps them stroke-matched to
 * one another. They inherit colour from the surrounding text via currentColor and
 * are marked aria-hidden, because every icon here sits next to a real text label.
 */
interface IconProps {
  className?: string;
}

function Svg({ className, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className ?? 'h-5 w-5'}
    >
      {children}
    </svg>
  );
}

